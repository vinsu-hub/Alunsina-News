ALTER TABLE contributors ADD COLUMN verified_at timestamptz, ADD COLUMN region text,
 ADD COLUMN source_id text REFERENCES sources(id) ON DELETE SET NULL, ADD COLUMN active boolean NOT NULL DEFAULT true;
ALTER TABLE stories ADD COLUMN hidden boolean NOT NULL DEFAULT false;
ALTER TABLE flags ADD COLUMN resolved_at timestamptz, ADD COLUMN resolution_note text,
 ADD CONSTRAINT flags_status_check CHECK (status IN ('open','resolved','dismissed'));
CREATE TABLE pitches (
 pitch_id text PRIMARY KEY, reporter_id text NOT NULL REFERENCES contributors(id) ON DELETE CASCADE,
 topic text NOT NULL, region text, angle text NOT NULL, timeframe text NOT NULL,
 status text NOT NULL DEFAULT 'pitched' CHECK (status IN ('pitched','in_progress','published')),
 linked_blindspot_id integer REFERENCES blindspots(id) ON DELETE SET NULL,
 linked_story_id text REFERENCES stories(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 status_changed_at timestamptz NOT NULL DEFAULT now(),
 screening_status text NOT NULL DEFAULT 'pending' CHECK (screening_status IN ('pending','passed','flagged')),
 screening_categories jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(screening_categories) = 'array'), screened_at timestamptz
);
CREATE TABLE pitch_publications (
 pitch_id text PRIMARY KEY REFERENCES pitches(pitch_id) ON DELETE CASCADE,
 article_id text NOT NULL UNIQUE REFERENCES articles(id) ON DELETE CASCADE,
 url text NOT NULL, headline text NOT NULL, excerpt text NOT NULL,
 screening_status text NOT NULL DEFAULT 'pending' CHECK (screening_status IN ('pending','passed','flagged')),
 screening_categories jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(screening_categories) = 'array'), screened_at timestamptz
);
CREATE INDEX pitches_activity ON pitches(updated_at DESC);
CREATE INDEX pitches_reporter ON pitches(reporter_id);
CREATE TABLE admin_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at timestamptz NOT NULL DEFAULT now(),
 action text NOT NULL, entity text NOT NULL, entity_id text, detail jsonb NOT NULL DEFAULT '{}'
);
