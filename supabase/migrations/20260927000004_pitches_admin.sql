-- These views are used only through the server DB owner, never PostgREST.
CREATE VIEW public_articles AS SELECT a.* FROM articles a
 WHERE NOT EXISTS (SELECT 1 FROM pitch_publications p WHERE p.article_id=a.id AND p.screening_status <> 'passed')
 AND NOT EXISTS (SELECT 1 FROM stories s WHERE s.id=a.story_id AND s.hidden);
CREATE VIEW public_stories AS SELECT s.* FROM stories s WHERE NOT hidden
 AND EXISTS (SELECT 1 FROM public_articles a WHERE a.story_id=s.id);
